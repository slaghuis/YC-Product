type SKUOptions struct {
  Options	[]uint  `json:"options"`     // selectedOptionIDs = []uint{optionIDForSmall, optionIDForRed}
}

func (h *Handler) GetSKUfromProductOptions(c *gin.Context) {
	id := c.Param("id")
	productID, err := h.StrToUint(id)
  if err != nil {
    c.JSON(http.StatusBadRequest, gin.H{
      "status": "error",
      "message": "failed to parse product id: " + err.Error(),
    })
    return
  }

	// selectedOptionIDs = []uint{optionIDForSmall, optionIDForRed}
	var req SKUOptions
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{
      "status": "error",
      "message": "failed to parse options list: " + err.Error(),
    })
		return
	}

	// h.LogJson(req)

	var sku models.SKU
	err = h.db.
    	Preload("Options").
    	Joins("JOIN sku_options ON sku_options.sk_uid = skus.id").
    	Where("skus.product_id = ?", productID).
    	Where("sku_options.option_id IN ?", req.Options).
    	Group("skus.id").
    	Having("COUNT(sku_options.option_id) = ?", len(req.Options)).
    	First(&sku).Error

	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{
      "status": "error",
      "message": "SKU not found: " + err.Error(),
    })
		return
	}
	c.JSON(http.StatusOK, &sku)
}
