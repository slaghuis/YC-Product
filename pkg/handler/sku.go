type CreateSKURequest struct {
    OptionIDs []uint  `json:"option_ids"`
    Price     float64 `json:"price"`
    Stock     int     `json:"stock"`
}

func (h *Handler) CreateSKUHandler(c *gin.Context) {
	token := c.GetString("token_key")
	id := c.Param("id")

	var req struct {
		OptionIDs []uint  `json:"option_ids" binding:"required"`
    Price     float64 `json:"price" binding:"required"`
    Stock     int     `json:"stock"`
  }
  if err := c.ShouldBindJSON(&req); err != nil {
      c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
      return
  }

	sku, err := h.SkuService.CreateSKU(c, id, req.OptionIDs, req.Price, req.Stock, token)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

  c.JSON(http.StatusCreated, sku)
}

type CreateAllSKURequest struct {
    Price     float64 `json:"price"`
    Stock     int     `json:"stock"`
}

func (h *Handler) CreateAllSKUsHandler(c *gin.Context) {
  var req CreateAllSKURequest
  if err := c.ShouldBindJSON(&req); err != nil {
      c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
      return
  }

  productID, _ := strconv.Atoi(c.Param("id"))
  var product models.Product
  if err := h.db.First(&product, productID).Error; err != nil {
      c.JSON(http.StatusNotFound, gin.H{"error": "Product not found"})
      return
  }
  skus, err := models.GenerateAllSKUs(h.db, product, req.Price, req.Stock)
  if err != nil {
      c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
      return
  }

  c.JSON(http.StatusCreated, skus)
}

