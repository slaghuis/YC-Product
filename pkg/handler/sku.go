// Handle auth.DELETE("/skus/:id", h.DeleteSKUHandler)
func (h *Handler) DeleteSKUHandler(c *gin.Context) {
  id := c.Param("id")

  if result := h.db.Delete(&models.SKU{}, id); result.Error != nil {
      c.AbortWithError(http.StatusInternalServerError, result.Error)
      return
  }

  c.JSON(http.StatusOK, gin.H{
    "status": "success",
    "message": "SKU successfully deleted",
  })
}

